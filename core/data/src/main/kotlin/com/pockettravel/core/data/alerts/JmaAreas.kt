    /** Codice dell'ufficio che comprende la zona di previsione [zoneCode]. */
    fun officeOf(zoneCode: String): String =
        OFFICE_OF_ZONE[zoneCode] ?: zoneCode.takeIf { it in OFFICES } ?: (zoneCode.take(OFFICE_PREFIX) + "00")

    /** Nome inglese dell'ufficio, nullo se il codice e' sconosciuto. */
    fun officeName(code: String): String? = OFFICES[code]

    /** Nome inglese della zona di previsione, nullo se il codice e' sconosciuto. */
    fun zoneName(code: String): String? = ZONES[code]

    /** Quante zone di previsione ha l'ufficio. */
    fun zoneCount(officeCode: String): Int = ZONES.keys.count { officeOf(it) == officeCode }
